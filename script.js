let dialogState = { slides: [], index: 0, sourceImage: null, zoomButton: null };

const dialog = document.getElementById('image-dialog');
const dialogImg = document.getElementById('dialog-image');
const dialogCount = document.getElementById('dialog-count');
const dialogPrev = document.getElementById('dialog-prev');
const dialogNext = document.getElementById('dialog-next');
const closeDialog = document.getElementById('dialog-close');

function renderDialog(){
  const {slides,index} = dialogState;
  if(!slides.length) return;
  dialogImg.src = slides[index][0];
  dialogImg.alt = slides[index][1];
  dialogCount.textContent = `${index+1} de ${slides.length}`;
  dialogPrev.disabled = index === 0;
  dialogNext.disabled = index === slides.length - 1;
}

function openDialog(slides,index,sourceImage,zoomButton){
  dialogState = {slides,index,sourceImage,zoomButton};
  renderDialog();
  if(typeof dialog.showModal === 'function') dialog.showModal();
}

function moveDialog(delta){
  const nextIndex = dialogState.index + delta;
  if(nextIndex < 0 || nextIndex >= dialogState.slides.length) return;
  dialogState.index = nextIndex;
  renderDialog();
}

function initCarousel(article){
  const key = article.dataset.carousel;
  const slides = carouselData[key];
  let index = 0;
  const img = article.querySelector('.carousel-stage img');
  const count = article.querySelector('.carousel-count');
  const prev = article.querySelector('.carousel-prev');
  const next = article.querySelector('.carousel-next');
  const zoom = article.querySelector('.zoom-slide');
  const carousel = article.querySelector('.carousel');

  function render(){
    img.src = slides[index][0];
    img.alt = slides[index][1];
    count.textContent = `${index+1} de ${slides.length}`;
    prev.disabled = index === 0;
    next.disabled = index === slides.length-1;
  }
  prev.addEventListener('click',()=>{ if(index>0){index--;render();} });
  next.addEventListener('click',()=>{ if(index<slides.length-1){index++;render();} });
  carousel.addEventListener('keydown',(e)=>{
    if(e.key==='ArrowLeft' && index>0){e.preventDefault();index--;render();}
    if(e.key==='ArrowRight' && index<slides.length-1){e.preventDefault();index++;render();}
  });
  zoom.addEventListener('click',()=>openDialog(slides,index,img,zoom));
  render();
}

document.querySelectorAll('[data-carousel]').forEach(initCarousel);

dialogPrev.addEventListener('click',()=>moveDialog(-1));
dialogNext.addEventListener('click',()=>moveDialog(1));
closeDialog.addEventListener('click',()=>dialog.close());
dialog.addEventListener('click',(e)=>{ if(e.target===dialog) dialog.close(); });
dialog.addEventListener('keydown',(e)=>{
  if(e.key==='ArrowLeft'){e.preventDefault();moveDialog(-1);}
  if(e.key==='ArrowRight'){e.preventDefault();moveDialog(1);}
});
dialog.addEventListener('close',()=>{
  if(dialogState.zoomButton) dialogState.zoomButton.focus();
});

let scale = 1;
const root = document.documentElement;
document.querySelector('[data-access="larger"]').addEventListener('click',()=>{scale=Math.min(1.35,+(scale+0.1).toFixed(2));root.style.setProperty('--text-scale',scale);});
document.querySelector('[data-access="smaller"]').addEventListener('click',()=>{scale=Math.max(.9,+(scale-0.1).toFixed(2));root.style.setProperty('--text-scale',scale);});
